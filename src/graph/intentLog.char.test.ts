// Nondeterminism removed by:
//   - vi.useFakeTimers() + vi.setSystemTime('2026-01-01T00:00:00.000Z'): all
//     new Date() calls inside the store are frozen; vi.advanceTimersByTime(100)
//     is called between lifecycle phases to produce distinct timestamps.
//   - normalizeLog(): post-normalizes the raw log AFTER collection, replacing
//     every nanoid-generated ID and ISO timestamp with a stable alias scoped to
//     the log itself (first-seen order within the log, grouped by prefix):
//       · evt_AbCd1234 → evt_001, evt_002, …  (event identity)
//       · run_XyZw5678 → run_001, …           (RunRecord id)
//       · ver_Mn0p9876 → ver_001, …           (OutputVersion id)
//       · result_Qq1r2s3t → result_001, …    (auto-created result Card id)
//       · conn_Uu4v5w6x → conn_001, …        (auto-created Connection id)
//       · blk_Yy7z8901 → blk_001, …          (block id inside result Card)
//       · "2026-01-01T00:00:00.000Z" → T0     (timestamp aliases)
//     Static user-defined IDs (ask-1, note-1, conn-n1-ask, …) are never
//     generated by newId() and are never altered — they appear byte-exact.
//     The commit funnel's causal stamps (#188/#189, ADR 0016) normalize the
//     same way: commitId → commit_001…, actorId → actor_001…, clientTxnId →
//     txn_001… — so commit BOUNDARIES stay pinned (events born from one
//     mutation share one commit alias; a refactor that splits or merges
//     commits changes the snapshot). seq is deterministic and stays numeric.
//     All other data (event types, payloads, order) is byte-exact.
//   - BLOCKER-FIX (undo/redo): the baseline after a card move is taken via
//     structuredClone() so that in-place mutations would be caught.

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { Card, IntentLogEvent } from './types'
import { useGraph } from './store'

// ---- Post-normalization --------------------------------------------------------
//
// Replace every nanoid-generated ID (exactly 8 chars from [A-Za-z0-9_-]) and every
// ISO-8601 timestamp with stable first-seen-order aliases scoped to the log.
// This decouples the snapshot from allocation order — a refactor that preserves
// event semantics but reorders internal newId() calls will not change the snapshot.
function normalizeLog(log: IntentLogEvent[]): unknown {
  const raw = JSON.stringify(log, null, 2)

  // Match nanoid-generated IDs as JSON string values — quoted in the raw JSON.
  // Format: one or more lowercase letters, underscore, then exactly 8 chars
  // from the nanoid alphabet [A-Za-z0-9_-].  Matching the surrounding quotes
  // avoids word-boundary failures when the last char of the ID is '-' (not a
  // word char, so \b would not fire there).
  const idRe = /"([a-z]+_[A-Za-z0-9_-]{8})"/g
  const prefixCounters = new Map<string, number>()
  const idAliases = new Map<string, string>()

  let m: RegExpExecArray | null
  while ((m = idRe.exec(raw)) !== null) {
    const full = m[1]  // ID without quotes
    if (!idAliases.has(full)) {
      const prefix = full.slice(0, full.indexOf('_'))
      const n = (prefixCounters.get(prefix) ?? 0) + 1
      prefixCounters.set(prefix, n)
      idAliases.set(full, `${prefix}_${String(n).padStart(3, '0')}`)
    }
  }

  // ISO-8601 timestamps: replace each unique timestamp in first-seen order.
  const tsRe = /"(\d{4}-\d{2}-\d{2}T[^"]+)"/g
  const tsAliases = new Map<string, string>()
  let tsCount = 0
  while ((m = tsRe.exec(raw)) !== null) {
    const ts = m[1]
    if (!tsAliases.has(ts)) tsAliases.set(ts, `T${tsCount++}`)
  }

  // Apply all replacements (quoted, so only exact JSON string values match).
  let result = raw
  for (const [id, alias] of idAliases) result = result.split(`"${id}"`).join(`"${alias}"`)
  for (const [ts, alias] of tsAliases) result = result.split(`"${ts}"`).join(`"${alias}"`)

  return JSON.parse(result)
}

// ---- Helpers -------------------------------------------------------------------

function card(id: string, kind: Card['kind'], position = { x: 100, y: 100 }): Card {
  return {
    id,
    kind,
    blocks: [{ id: `${id}-blk`, text: '' }],
    position,
  }
}

function resetStore() {
  useGraph.setState({
    cards: [],
    connections: [],
    outputs: [],
    runs: [],
    intentLog: [],
    selection: null,
    selectedCardIds: [],
    undoStack: [],
    redoStack: [],
    saveState: 'saved',
    hydrated: false,
    currentIdeaId: null,
    keyPromptOpen: false,
    ideaManagerOpen: false,
  })
}

// ---- Compiled fixtures ---------------------------------------------------------
//
// RICH_COMPILED is used for scenario 1 (the "representative run") so the snapshot
// pins usedConnectionIds, usedGroupDigests, appliedMods, and contextBudget.
// A refactor that corrupts any of these RunRecord fields will change the snapshot.
// IDs within this object are static (user-controlled, non-nanoid) and appear
// byte-exact in the normalized snapshot.
const RICH_COMPILED = {
  text: 'Characterization test instruction with rich context.',
  model: 'claude-test',
  usedCardIds: ['ask-1', 'note-1', 'note-2'] as string[],
  usedConnectionIds: ['conn-n1-ask', 'conn-n2-ask'] as string[],
  usedGroupDigests: [{ groupCardId: 'group-1', versionId: 'gd-ver-1', connectionId: 'conn-grp-ask' }],
  modIds: ['mod-1'] as string[],
  appliedMods: [{ modCardId: 'mod-1', controlValues: { novelty: 7 } as Record<string, unknown>, appliedInstructions: ['Be creative.'] }],
  contextBudget: {
    budgetTokens: 4000,
    estimatedTokens: 3500,
    finalTokens: 3500,
    compactedCardIds: [] as string[],
    droppedCardIds: [] as string[],
    mode: 'when-needed' as const,
  },
}

// Lean fixture for scenarios that test edge-case semantics, not field coverage.
const LEAN_COMPILED = {
  text: 'Characterization test instruction.',
  model: 'claude-test',
  usedCardIds: ['ask-1'] as string[],
  usedConnectionIds: [] as string[],
  modIds: [] as string[],
  appliedMods: [] as [],
}

// ---- Scenarios -----------------------------------------------------------------

describe('Intent Log characterization — byte-stable snapshots', () => {
  beforeEach(() => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-01-01T00:00:00.000Z'))
    resetStore()
  })

  afterEach(() => {
    vi.useRealTimers()
  })

  // Scenario 1: representative ask-AI run from start to finish.
  // RICH_COMPILED pins usedConnectionIds, usedGroupDigests, appliedMods, contextBudget
  // so a refactor that corrupts those RunRecord fields changes this snapshot.
  // Expected events: card.created (auto result card) · connection.created ·
  //                  run.started · run.completed
  it('scenario 1 — representative run end-to-end', () => {
    useGraph.setState({
      cards: [
        card('ask-1', 'askAi'),
        card('note-1', 'note'),
        card('note-2', 'note'),
      ],
    })

    const { runId, versionId } = useGraph.getState().beginRun('ask-1', RICH_COMPILED)

    // Simulate streaming — appendVersionText never emits log events.
    useGraph.getState().appendVersionText(versionId, 'Hello world')

    vi.advanceTimersByTime(100) // finishRun gets a distinct timestamp (T1)

    useGraph.getState().finishRun(runId)

    expect(normalizeLog(useGraph.getState().intentLog)).toMatchSnapshot()
  })

  // Scenario 2: cancel mid-stream.
  // Expected events: card.created · connection.created · run.started · run.canceled
  it('scenario 2 — cancel mid-stream', () => {
    useGraph.setState({ cards: [card('ask-2', 'askAi')] })

    const compiled = { ...LEAN_COMPILED, usedCardIds: ['ask-2'] as string[] }
    const { runId, versionId } = useGraph.getState().beginRun('ask-2', compiled)

    useGraph.getState().appendVersionText(versionId, 'Partial...')

    vi.advanceTimersByTime(100)

    useGraph.getState().cancelRun(runId)

    expect(normalizeLog(useGraph.getState().intentLog)).toMatchSnapshot()
  })

  // Scenario 3: no-op structural update — must emit zero events.
  // Routed through the real moveCard action (same-position move) so the test
  // exercises the full user-facing code path, not just the internal helper.
  // Pins the length-guarded semantics: an update that produces no structural
  // diff pushes no undo entry and appends no Intent Log event.
  it('scenario 3 — no-op structural update emits nothing', () => {
    useGraph.setState({ cards: [card('note-1', 'note', { x: 50, y: 50 })] })

    // Move to the same position — the structural diff is empty.
    useGraph.getState().moveCard('note-1', { x: 50, y: 50 })

    expect(useGraph.getState().intentLog).toHaveLength(0)
    expect(useGraph.getState().undoStack).toHaveLength(0)
  })

  // Scenario 4: chained run — two sequential runs on the same ask-AI card.
  // Run 1 creates the result card and connection (card.created · connection.created).
  // Run 2 finds the existing result card — no card.created or connection.created.
  // Full log: card.created · connection.created ·
  //           run.started · run.completed (run 1) ·
  //           run.started · run.completed (run 2)
  it('scenario 4 — chained run (two runs on same card)', () => {
    useGraph.setState({ cards: [card('ask-1', 'askAi')] })

    const { runId: runId1 } = useGraph.getState().beginRun('ask-1', LEAN_COMPILED)

    vi.advanceTimersByTime(100)
    useGraph.getState().finishRun(runId1)

    vi.advanceTimersByTime(100)
    const { runId: runId2 } = useGraph.getState().beginRun('ask-1', LEAN_COMPILED)

    vi.advanceTimersByTime(100)
    useGraph.getState().finishRun(runId2)

    expect(normalizeLog(useGraph.getState().intentLog)).toMatchSnapshot()
  })

  // Scenario 5: undo/redo round-trip.
  // The Intent Log is append-only: undo reverts the board but must not remove or
  // mutate any log entry. Redo re-applies the board change but must not add any
  // log entry. Baseline is taken with structuredClone so an in-place mutation of
  // the live array or its objects would be detected.
  it('scenario 5 — undo/redo does not mutate the Intent Log', () => {
    useGraph.setState({ cards: [card('note-1', 'note', { x: 0, y: 0 })] })

    useGraph.getState().moveCard('note-1', { x: 200, y: 200 })

    // Deep-clone the baseline BEFORE undo so any in-place mutation is caught.
    const logBaseline = structuredClone(useGraph.getState().intentLog)
    expect(logBaseline).toHaveLength(1)
    expect(logBaseline[0].type).toBe('card.moved')

    // Undo: board reverts; log must remain identical to baseline.
    useGraph.getState().undo()
    expect(useGraph.getState().intentLog).toHaveLength(1)
    expect(useGraph.getState().intentLog).toStrictEqual(logBaseline)
    expect(useGraph.getState().cards.find((c) => c.id === 'note-1')?.position).toEqual({ x: 0, y: 0 })

    // Redo: board re-applies; log must still be identical to baseline.
    useGraph.getState().redo()
    expect(useGraph.getState().intentLog).toHaveLength(1)
    expect(useGraph.getState().intentLog).toStrictEqual(logBaseline)
    expect(useGraph.getState().cards.find((c) => c.id === 'note-1')?.position).toEqual({ x: 200, y: 200 })

    // Snapshot the normalized log for byte-stability across refactors.
    expect(normalizeLog(useGraph.getState().intentLog)).toMatchSnapshot()
  })
})
