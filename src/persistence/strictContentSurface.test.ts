// THE HARD STOP, AS A CHECK INSTEAD OF A SENTENCE.
//
// docs/agents/persisting-a-new-setting.md forbids two moves, and they are the
// two that caused the incident the settings envelope exists to prevent:
//
//   hard stop 1: adding a key to a strict `hasOnlyKeys` or `hasExactKeys`
//                allowlist for something that is presentation or preference.
//   hard stop 3: widening a closed value union on the strict path to carry a
//                preference.
//
// Until this file existed, both were enforced by prose. The 78-row rejection
// table in settingsEnvelope.test.ts pins the FROZEN validators, the fixture
// corpus pins itself with a digest, and nothing at all held the LIVE strict
// allowlists. A contributor could add one key to `validateCard` and ship a
// Profile that every installed build refuses, with a green suite the whole way.
//
// So the live surface is pinned here, by hand, in a table a reader can argue
// with. It is deliberately NOT a snapshot file: a snapshot gets regenerated by
// reflex, and the entire value of this check is the moment where somebody has
// to stop and decide which of two things they are doing.
//
// WHAT IS NOT PINNED, ON PURPOSE
//
// Everything inside a settings envelope: `Card.meta`, `Board.settings`,
// `Idea.settings`, `Board.aiSettings`. The envelope KEY appears below, because
// the strict allowlist has to admit the container, but its contents are free to
// grow forever and must stay that way. That growth is the correct move, and
// settingsEnvelope.test.ts is where it is proven safe.
//
// Also not pinned: the Run, intent-history, Mod, Highlight, and Profile-record
// validators. They carry execution history and identity, which no preference
// has ever tried to join. The prose hard stop still covers them. If one ever
// does attract a setting, add it to this table then.
