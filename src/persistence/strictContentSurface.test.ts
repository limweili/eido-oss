type KeyPin = {
  // The validator the list gates, named as a reader would grep for it.
  validator: string
  // Content keys: strict, fail closed, and pinned.
  content: readonly string[]
  // The record's settings envelope container. On the allowlist, and everything
  // inside it is out of this pin's reach.
  envelope: readonly string[]
  // Where a preference on this record belongs instead.
  instead: string
}

