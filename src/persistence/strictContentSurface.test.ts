const SOP = 'docs/agents/persisting-a-new-setting.md'

function driftHeading(
  headline: string,
  added: readonly string[],
  removed: readonly string[],
): readonly string[] {
  return [
    headline,
    ...added.length > 0 ? [`  ADDED: ${added.join(', ')}`] : [],
    ...removed.length > 0 ? [`  REMOVED: ${removed.join(', ')}`] : [],
  ]
}

function keyDriftMessage(
  entry: string,
  pin: KeyPin,
  added: readonly string[],
  removed: readonly string[],
): string {
  return [
    ...driftHeading(
      `${pin.validator} no longer matches its pin in strictContentSurface.test.ts.`,
      added,
      removed,
    ),
    '',
    'Every key on this list is CONTENT and fails closed. Each build already',
    'installed carries its own copy of the list, refuses any record holding a key',
    'it was not compiled to know, and the revision store reports that refusal as a',
    'corrupt Profile for every Board the person owns (ADR 0040).',
    '',
    'Exactly one of these is true. Which one decides what you do next.',
    '',
    '1. IT IS CONTENT. The canvas, the semantic context, or a Run reads it to',
    '   decide what the record MEANS, and an older build SHOULD refuse a record',
    '   it cannot understand. Then this pin is out of date on purpose: update',
    `   KEY_PIN.${entry} in this file in the same commit, say so in the PR, and`,
    `   prove the downgrade outcome you claim (SOP 4, ${SOP}).`,
    '',
    '2. IT IS A SETTING OR PRESENTATION STATE. Its absence only costs a default',
    '   look, or state that would be wrong to lose on a second machine. Then it',
    '   must not be on this list at all, and no pin update makes it safe.',
    `   Where it belongs instead: ${pin.instead}.`,
    '   Declare it once with defineSetting or defineChoiceSetting and read it',
    '   through the envelope helpers. Nothing inside an envelope is pinned by',
    `   this test, so growing one is free. See SOP 2B in ${SOP}.`,
    '',
    'Unsure still means setting. Content misfiled as a setting costs one feature',
    'its stored state. A setting misfiled as content costs a person every Board.',
  ].join('\n')
}

function valueDriftMessage(
  entry: string,
  pin: ValuePin,
  added: readonly string[],
  removed: readonly string[],
): string {
  return [
    ...driftHeading(
      `The closed value set for ${pin.field} no longer matches its pin in strictContentSurface.test.ts.`,
      added,
      removed,
    ),
    '',
    'A new member of a closed set on the strict path costs exactly what a new key',
    'costs. The older build was not compiled to accept the value, so it refuses the',
    'record carrying it, and one unfamiliar value becomes a corrupt Profile',
    '(ADR 0040, hard stop 3).',
    '',
    'Exactly one of these is true.',
    '',
    '1. IT IS CONTENT and an older build SHOULD refuse it. Then update',
    `   VALUE_PIN.${entry} in this file in the same commit, say so in the PR, and`,
    `   prove the downgrade outcome you claim (SOP 4, ${SOP}).`,
    '',
    '2. IT IS A PREFERENCE, meaning a build that cannot read the value should just',
    '   show the default. Then it does not belong in this set.',
    `   Where it belongs instead: ${pin.instead}.`,
    '   Inside an envelope the rule inverts: widen the setting contract\'s',
    '   `choices` or `accepts` freely, because a value this build cannot read',
    `   already resolves to the documented default. See SOP 2B in ${SOP}.`,
  ].join('\n')
}

function difference(left: readonly string[], right: readonly string[]): readonly string[] {
  const known = new Set(right)
  return left.filter((value) => !known.has(value))
}

describe('The strict content surface is pinned (ADR 0040 hard stops 1 and 3)', () => {
  it('pins every strict content validator the surface declares', () => {
    expect(
      Object.keys(STRICT_CONTENT_SURFACE.keys).sort(),
      'A strict content key list joined or left STRICT_CONTENT_SURFACE without a pin.\n'
      + `Add or remove the matching entry in KEY_PIN, and read SOP 1 in ${SOP} first:\n`
      + 'a validator that needs a settings envelope needs one before it needs a pin.',
    ).toEqual(Object.keys(KEY_PIN).sort())

    expect(
      Object.keys(STRICT_CONTENT_SURFACE.closedValues).sort(),
      'A closed value set joined or left STRICT_CONTENT_SURFACE without a pin.\n'
      + 'Add or remove the matching entry in VALUE_PIN. A NEW closed set on the strict\n'
      + `path is itself a decision: read SOP 1 in ${SOP} before adding one.`,
    ).toEqual(Object.keys(VALUE_PIN).sort())
  })

  for (const [entry, pin] of Object.entries(KEY_PIN)) {
    it(`holds the strict key allowlist of ${pin.validator}`, () => {
      const live = STRICT_CONTENT_SURFACE.keys[entry as keyof typeof STRICT_CONTENT_SURFACE.keys]
      const pinned = [...pin.content, ...pin.envelope]
      const added = difference(live, pinned)
      const removed = difference(pinned, live)
      expect({ added, removed }, keyDriftMessage(entry, pin, added, removed))
        .toEqual({ added: [], removed: [] })
    })
  }

  for (const [entry, pin] of Object.entries(VALUE_PIN)) {
    it(`holds the closed value set of ${pin.field}`, () => {
      const live = STRICT_CONTENT_SURFACE.closedValues[
        entry as keyof typeof STRICT_CONTENT_SURFACE.closedValues
      ]
      const added = difference(live, pin.members)
      const removed = difference(pin.members, live)
      expect({ added, removed }, valueDriftMessage(entry, pin, added, removed))
        .toEqual({ added: [], removed: [] })
    })
  }

  // The split between `content` and `envelope` above is the whole point of the
  // table, so it cannot be allowed to blur. An envelope key listed as content
  // would mean a later reader treats the container as pinned content and starts
  // asking permission to add settings, which is the opposite of ADR 0040.
  //
  // `connection.meta` is NOT one of these. It shares a name with the Card's
  // envelope and is content: an open record whose two known fields are checked
  // by value, so it stays in the content half.
  const ENVELOPE_CONTAINERS: Partial<Record<keyof typeof KEY_PIN, readonly string[]>> = {
    board: ['aiSettings', 'settings'],
    idea: ['settings'],
    card: ['meta'],
  }

  it('pins each settings envelope as a container and never as content', () => {
    for (const [entry, pin] of Object.entries(KEY_PIN)) {
      const containers = ENVELOPE_CONTAINERS[entry as keyof typeof KEY_PIN] ?? []
      const advice = 'An envelope is pinned as a container and nothing else. What goes inside\n'
        + 'it is pinned by nothing, and growing it is always allowed (ADR 0040).'
      expect(
        [...pin.envelope].sort(),
        `KEY_PIN.${entry} does not describe its settings envelope correctly.\n${advice}`,
      ).toEqual([...containers].sort())
      expect(
        pin.content.filter((key) => containers.includes(key)),
        `KEY_PIN.${entry} lists its own settings envelope in the content half.\n${advice}`,
      ).toEqual([])
    }
  })

  // A pin held against a list nothing reads is decoration. These two tests keep
  // the table attached to the running validators: the lists are what the live
  // code gates with, and the gate really does refuse a stranger key.
  it('keeps every pinned list wired into the validator it gates', () => {
    const source = readFileSync('src/persistence/profileLogicalProjection.ts', 'utf8')
    for (const [entry, pin] of Object.entries(KEY_PIN)) {
      expect(
        source,
        `${pin.validator} must gate with STRICT_CONTENT_SURFACE.keys.${entry}.\n`
        + 'An inline key list beside it would be invisible to this pin, which is the\n'
        + 'exact hole this file was written to close.',
      ).toContain(`STRICT_CONTENT_SURFACE.keys.${entry}`)
    }
    for (const entry of Object.keys(VALUE_PIN)) {
      expect(
        source,
        `A closed value check must read STRICT_CONTENT_SURFACE.closedValues.${entry}\n`
        + 'rather than an inline list, or this pin holds nothing.',
      ).toContain(`STRICT_CONTENT_SURFACE.closedValues.${entry}`)
    }
  })

  // The cost the messages above describe, shown once rather than asserted. The
  // tolerant half, meaning an unknown key INSIDE an envelope surviving a load,
  // is proven in settingsEnvelope.test.ts and is not repeated here.
  it('still refuses a stranger key on a Card, a Board, and an Idea', () => {
    const fixture = createCompleteProfileFixture()
    const stranger = 'futureStrictKey'

    const onCard = structuredClone(fixture.snapshot)
    Object.assign(onCard.boards['idea-main']!.cards[0]!, { [stranger]: 'value' })
    expect(() => projectProfileSnapshot(onCard, fixture.projectAsset))
      .toThrow(ProfileLogicalProjectionError)

    const onBoard = structuredClone(fixture.snapshot)
    Object.assign(onBoard.boards['idea-main']!, { [stranger]: 'value' })
    expect(() => projectProfileSnapshot(onBoard, fixture.projectAsset))
      .toThrow(ProfileLogicalProjectionError)

    const onIdea = structuredClone(fixture.snapshot)
    Object.assign(onIdea.ideas[0]!, { [stranger]: 'value' })
    expect(() => projectProfileSnapshot(onIdea, fixture.projectAsset))
      .toThrow(ProfileLogicalProjectionError)
  })
})
